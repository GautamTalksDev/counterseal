#!/usr/bin/env node
// Apply server/src/brand.js everywhere. Run from the repo root after editing brand.js:
//   node scripts/rebrand.mjs           rewrite the previous values (brand.lock.json) to the new ones, regenerate
//                                      site/public/brand.js, update the lock
//   node scripts/rebrand.mjs --check   exit 1 if anything is out of step (CI runs this through server/test/brand.test.js)
// Exact, case-sensitive replacement of whole values only, in user-facing text files: the site, the README, SECURITY.md,
// docs/, the CLI and the SDK. Internal identifiers are never touched (see the comment in brand.js). Review the diff:
// a domain or package name change also rewrites install lines and URLs, which must already work.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { BRAND } from '../server/src/brand.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const LOCK = join(ROOT, 'brand.lock.json');
// order matters: longer values first, so "https://x" is replaced before "x"
export const KEYS = ['origin', 'wordmark', 'tagline', 'recordLine', 'domain', 'sdk', 'cli', 'cliPlanned', 'name', 'repo'];
const TEXT = /\.(html|js|mjs|md|webmanifest|json|txt|yml)$/;
const SKIP = new Set(['fonts', 'img', 'node_modules', '.git', 'fixtures']);
const GENERATED = new Set(['site/public/brand.js', 'site/public/receipts-sdk.js', 'site/public/websig.js', 'brand.lock.json', 'site/public/shellmap.js', 'site/public/mcp/mcp-policy.mjs', 'site/public/mcp/mcp-sql.mjs', 'site/public/mcp/mcp-json.mjs']);

export function files() {
  const out = [];
  const walk = (dir) => {
    for (const n of readdirSync(dir)) {
      if (SKIP.has(n)) continue;
      const p = join(dir, n);
      if (statSync(p).isDirectory()) walk(p); else if (TEXT.test(n)) out.push(p);
    }
  };
  for (const d of ['site/public', 'docs', 'cli', 'sdk', 'plugins', 'action']) walk(join(ROOT, d));
  for (const f of ['README.md', 'SECURITY.md']) if (existsSync(join(ROOT, f))) out.push(join(ROOT, f));
  return out.filter((p) => !GENERATED.has(relative(ROOT, p).replaceAll('\\', '/')));
}

export const brandModule = () => `// Generated by scripts/rebrand.mjs from server/src/brand.js. Do not edit.\nexport const BRAND = ${JSON.stringify(BRAND, null, 2)};\n`;

// read in one step (no exists-then-read race); null when the file is not there
const readOrNull = (p) => { try { return readFileSync(p, 'utf8'); } catch (e) { if (e?.code === 'ENOENT') return null; throw e; } };

function main(check) {
  const lockText = readOrNull(LOCK);
  const lock = lockText != null ? JSON.parse(lockText) : { ...BRAND };
  const changes = KEYS.filter((k) => lock[k] && BRAND[k] && lock[k] !== BRAND[k]);
  let touched = 0;
  if (changes.length && !check) {
    for (const f of files()) {
      let s = readFileSync(f, 'utf8');
      const before = s;
      for (const k of changes) s = s.split(lock[k]).join(BRAND[k]);
      if (s !== before) { writeFileSync(f, s); touched++; }
    }
  }
  const mod = join(ROOT, 'site/public/brand.js');
  const want = brandModule();
  const stale = readOrNull(mod) !== want;
  if (check) {
    if (changes.length || stale) { console.error(`brand out of step: ${changes.length ? 'changed ' + changes.join(', ') + '; ' : ''}${stale ? 'site/public/brand.js is stale; ' : ''}run node scripts/rebrand.mjs`); return 1; }
    console.log('brand in step'); return 0;
  }
  writeFileSync(mod, want);
  // the site serves copies of two SDK files; keep them identical to the SDK
  writeFileSync(join(ROOT, 'site/public/receipts-sdk.js'), readFileSync(join(ROOT, 'sdk/receipts.mjs'), 'utf8').split('\n').slice(1).join('\n'));
  writeFileSync(join(ROOT, 'site/public/websig.js'), readFileSync(join(ROOT, 'sdk/websig.mjs'), 'utf8'));
  // the homepage runs the shell map and the MCP wrapper's policy as they are (identical copies)
  writeFileSync(join(ROOT, 'site/public/shellmap.js'), readFileSync(join(ROOT, 'sdk/shellmap.mjs'), 'utf8'));
  for (const f of ['mcp-policy.mjs', 'mcp-sql.mjs', 'mcp-json.mjs']) writeFileSync(join(ROOT, 'site/public/mcp', f), readFileSync(join(ROOT, 'cli', f), 'utf8'));
  writeFileSync(LOCK, JSON.stringify(Object.fromEntries(KEYS.map((k) => [k, BRAND[k]])), null, 2) + '\n');
  console.log(`rebranded ${touched} files (${changes.join(', ') || 'nothing changed'}); review with git diff`);
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = main(process.argv.includes('--check'));
